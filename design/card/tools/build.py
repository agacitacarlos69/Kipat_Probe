# ---------------------------------------------------------------------------- typography
@dataclass
class Face:
    path: Path

    def __post_init__(self):
        blob = hb.Blob.from_file_path(str(self.path))
        self.face = hb.Face(blob)
        self.font = hb.Font(self.face)
        self.upem = self.face.upem
        self.tt = TTFont(str(self.path))
        self.glyphs = self.tt.getGlyphSet()
        self.order = self.tt.getGlyphOrder()
        os2 = self.tt["OS/2"]
        self.cap = os2.sCapHeight / self.upem
        self.xh = os2.sxHeight / self.upem

    def _shape(self, text: str):
        buf = hb.Buffer()
        buf.add_str(text)
        buf.guess_segment_properties()
        hb.shape(self.font, buf, {"kern": True, "liga": True, "calt": True})
        return buf.glyph_infos, buf.glyph_positions

    def width(self, text: str, size_mm: float, tracking_em: float = 0.0) -> float:
        _, pos = self._shape(text)
        adv = sum(p.x_advance for p in pos) / self.upem
        return (adv + tracking_em * max(len(pos) - 1, 0)) * size_mm

    def outline(self, text: str, x: float, baseline: float, size_mm: float, tracking_em: float = 0.0, anchor: str = "start") -> str:
        """Text as an SVG path ('d'), outlined. Anchor: start | end."""
        infos, pos = self._shape(text)
        s = size_mm / self.upem
        if anchor == "end":
            x -= self.width(text, size_mm, tracking_em)
        pen_x = 0.0
        parts = []
        for info, p in zip(infos, pos):
            name = self.order[info.codepoint]
            sp = SVGPathPen(self.glyphs, ntos=lambda v: f"{v:.3f}".rstrip("0").rstrip("."))
            tp = TransformPen(sp, (s, 0, 0, -s, x + (pen_x + p.x_offset) * s, baseline - p.y_offset * s))
            self.glyphs[name].draw(tp)
            d = sp.getCommands()
            if d:
                parts.append(d)
            pen_x += p.x_advance + tracking_em * self.upem
        return " ".join(parts)


