# ---------------------------------------------------------------------------- SVG document
class Doc:
    def __init__(self, edition: Edition, side: str):
        self.e = edition
        self.side = side
        self.layers: dict[str, list[str]] = {k: [] for k in ["MATERIAL", "WHITE_INK", "CMYK", "SPOT_GLOSS", "DEBOSS", "NFC_SAFETY_ZONE", "GUIDES"]}

    def add(self, layer: str, svg: str):
        self.layers[layer].append(svg)

    def svg(self, mode: str = "master") -> str:
        """mode: master (plates/guides hidden) | proof (ink only) | finish (ink + plates) | guides (ink + guides)."""
        e = self.e
        vb = f"{fmt(-BLEED)} {fmt(-BLEED)} {fmt(W + 2 * BLEED)} {fmt(H + 2 * BLEED)}"
        out = [
            '<?xml version="1.0" encoding="UTF-8"?>',
            f'<svg xmlns="http://www.w3.org/2000/svg" xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape" '
            f'width="{fmt(W + 2 * BLEED)}mm" height="{fmt(H + 2 * BLEED)}mm" viewBox="{vb}" '
            f'data-edition="{e.key}" data-side="{self.side}">',
            f"<title>Kipat card, {html.escape(e.title)}, {self.side}</title>",
            "<desc>CR80 85.60 x 53.98 mm, corner radius 3.18 mm. Canvas includes a 3 mm working bleed; "
            "FINAL BLEED MUST FOLLOW THE SELECTED VENDOR'S TEMPLATE. Colours are digital references; "
            "FINAL PRINT COLOUR MUST BE PROOFED WITH THE VENDOR. Text is outlined Inter (SIL OFL). "
            "Plates SPOT_GLOSS / DEBOSS and NFC_SAFETY_ZONE / GUIDES are hidden and non-printing as colour.</desc>",
        ]
        visible = {
            "master": {"WHITE_INK", "CMYK"},
            "proof": {"CMYK"} | ({"WHITE_INK"} if e.frosted else set()),
            "finish": {"CMYK", "SPOT_GLOSS", "DEBOSS"} | ({"WHITE_INK"} if e.frosted else set()),
            "guides": {"CMYK", "GUIDES", "NFC_SAFETY_ZONE"} | ({"WHITE_INK"} if e.frosted else set()),
        }[mode]
        for name, items in self.layers.items():
            if name == "MATERIAL" and mode != "master":
                continue
            show = name in visible
            style = "" if show else ' style="display:none"'
            if mode == "finish" and name in ("SPOT_GLOSS", "DEBOSS"):
                style = ' opacity="0.85"'
            if mode == "master" and name == "WHITE_INK":
                style = ' style="display:none"'   # visible plate would cover the art in viewers; printer toggles it
            out.append(f'<g id="{name}" inkscape:groupmode="layer" inkscape:label="{name}"{style}>')
            out.extend(items)
            out.append("</g>")
        out.append("</svg>")
        return "\n".join(out)


def base_flood(d: Doc):
    e = d.e
    rect = f'<rect x="{fmt(-BLEED)}" y="{fmt(-BLEED)}" width="{fmt(W + 2 * BLEED)}" height="{fmt(H + 2 * BLEED)}"'
    d.add("MATERIAL", f'{rect} fill="none" data-material="{html.escape(e.material)}"/>')
    if e.frosted:
        # Frosted stock is the material itself: nothing printed as a flood.
        return
    d.add("CMYK", f'{rect} fill="{e.base}" id="flood"/>')


def guides(d: Doc):
    g = []
    g.append(f'<rect x="{fmt(-BLEED)}" y="{fmt(-BLEED)}" width="{fmt(W + 2 * BLEED)}" height="{fmt(H + 2 * BLEED)}" fill="none" stroke="#FF3B30" stroke-width="0.1" data-guide="bleed"/>')
    g.append(f'<rect x="0" y="0" width="{fmt(W)}" height="{fmt(H)}" rx="{RADIUS}" fill="none" stroke="#111" stroke-width="0.12" data-guide="trim"/>')
    g.append(f'<rect x="{SAFE}" y="{SAFE}" width="{fmt(W - 2 * SAFE)}" height="{fmt(H - 2 * SAFE)}" fill="none" stroke="#00A3FF" stroke-width="0.1" stroke-dasharray="0.6 0.6" data-guide="safe"/>')
    g.append(f'<rect x="{MARGIN}" y="{MARGIN}" width="{fmt(W - 2 * MARGIN)}" height="{fmt(H - 2 * MARGIN)}" fill="none" stroke="#00A3FF" stroke-width="0.06" data-guide="margin"/>')
    cx, cy = CONTACT
    g.append(f'<path d="M{fmt(cx)} 0V{fmt(H)}M0 {fmt(cy)}H{fmt(W)}" stroke="#00A3FF" stroke-width="0.05" stroke-dasharray="0.3 0.6" data-guide="contact-axes"/>')
    d.layers["GUIDES"].extend(g)
    d.add("NFC_SAFETY_ZONE",
          f'<rect x="0" y="0" width="{fmt(W)}" height="{fmt(H)}" rx="{RADIUS}" fill="#FFB800" fill-opacity="0.10" stroke="#FFB800" stroke-width="0.15" '
          f'data-config="Default = whole card: antenna geometry unknown. Replace with the inlay vendor drawing. No metallic foil, metal or conductive ink inside unless the vendor certifies the build."/>')


def white_fill(fragment: str) -> str:
    """Recolour a fragment to white for the underbase; stroked arcs stay stroked (white), fills become white."""
    import re
    out = re.sub(r'fill="#[0-9A-Fa-f]{6}"', 'fill="#FFFFFF"', fragment)
    out = out.replace('data-stroke="#', 'stroke="#')
    out = re.sub(r'stroke="#[0-9A-Fa-f]{6}"', 'stroke="#FFFFFF"', out)
    return out.replace(' data-keep', '')


def white_under(d: Doc, svg_fragment: str):
    """Frosted stock: everything printed in colour sits on an opaque white underbase."""
    if d.e.white_underbase:
        # Same geometry as the colour above it (vendor applies its own choke). Fill only: a stroke would halo.
        frag = svg_fragment.replace('fill="none"', 'fill="none" data-keep').replace('stroke="#', 'data-stroke="#')
        d.add("WHITE_INK", f'<g fill="#FFFFFF" class="underbase">{white_fill(frag)}</g>')


# ---------------------------------------------------------------------------- fronts
def front(e: Edition, monogram: str | None = None) -> Doc:
    d = Doc(e, "front")
    base_flood(d)
    cx, cy = CONTACT
    k = e.key

    if k == "graphite-precision":
        # One precision orbit around the contact point; one satellite on it.
        r = 15.0
        a = math.radians(-38)
        sx, sy = cx + r * math.cos(a), cy + r * math.sin(a)
        d.add("CMYK", f'<circle id="orbit" cx="{fmt(cx)}" cy="{fmt(cy)}" r="{fmt(r)}" fill="none" stroke="{C["graphite_line"]}" stroke-width="0.35"/>')
        d.add("CMYK", f'<circle id="satellite" cx="{fmt(sx)}" cy="{fmt(sy)}" r="0.55" fill="{e.ink}"/>')
        d.add("SPOT_GLOSS", f'<circle cx="{fmt(cx)}" cy="{fmt(cy)}" r="{fmt(r)}" fill="none" stroke="{C["spot"]}" stroke-width="1.0" data-finish="raised spot gloss, 1.0 mm band over a 0.35 mm line: tolerates registration"/>')
        d.add("SPOT_GLOSS", f'<circle cx="{fmt(cx)}" cy="{fmt(cy)}" r="{fmt(CONTACT_R + 0.2)}" fill="{C["spot"]}"/>')

    elif k == "frosted-contact":
        # Touch makes a mark: two soft white rings spread from the contact point.
        for r, op in ((5.5, 1.0), (10.5, 0.55)):
            d.add("WHITE_INK", f'<circle cx="{fmt(cx)}" cy="{fmt(cy)}" r="{fmt(r)}" fill="none" stroke="#FFFFFF" stroke-width="0.3" opacity="{op}" data-note="white ink only"/>')

    elif k == "architectural-line":
        # One line enters from the left edge, turns once, and ends at the contact point.
        y = 41.0
        path = f"M{fmt(-BLEED)} {fmt(y)}H{fmt(cx)}V{fmt(cy)}"
        d.add("CMYK", f'<path id="line" d="{path}" fill="none" stroke="{e.ink}" stroke-width="0.5" stroke-linejoin="miter"/>')
        gloss = f"M{fmt(SAFE)} {fmt(y)}H{fmt(cx)}V{fmt(cy)}"   # raised gloss never enters the bleed / outside the safe zone
        d.add("SPOT_GLOSS", f'<path d="{gloss}" fill="none" stroke="{C["spot"]}" stroke-width="1.0" stroke-linejoin="miter" data-finish="raised spot gloss, 1.0 mm band"/>')

    elif k == "aperture":
        # One flat aperture: six segments with slanted cuts around a round opening. Not a camera shutter.
        R, r_in, twist = 11.0, 5.2, math.radians(24)
        blades, gaps = [], []
        for i in range(6):
            t0 = math.radians(60 * i - 90)
            t1 = t0 + math.radians(60)
            i0 = (cx + r_in * math.cos(t0), cy + r_in * math.sin(t0))
            i1 = (cx + r_in * math.cos(t1), cy + r_in * math.sin(t1))
            o0 = (cx + R * math.cos(t0 + twist), cy + R * math.sin(t0 + twist))
            o1 = (cx + R * math.cos(t1 + twist), cy + R * math.sin(t1 + twist))
            blades.append(
                f"M{fmt(i0[0])} {fmt(i0[1])}A{fmt(r_in)} {fmt(r_in)} 0 0 1 {fmt(i1[0])} {fmt(i1[1])}"
                f"L{fmt(o1[0])} {fmt(o1[1])}A{fmt(R)} {fmt(R)} 0 0 0 {fmt(o0[0])} {fmt(o0[1])}Z"
            )
            gaps.append(f"M{fmt(i0[0])} {fmt(i0[1])}L{fmt(o0[0])} {fmt(o0[1])}")
        bd = "".join(blades)
        d.add("CMYK", f'<path id="aperture" d="{bd}" fill="{C["blade"]}" fill-rule="nonzero"/>')
        d.add("CMYK", f'<path id="aperture-cuts" d="{"".join(gaps)}" stroke="{e.base}" stroke-width="0.5" stroke-linecap="square"/>')
        d.add("SPOT_GLOSS", f'<path d="{bd}" fill="{C["spot"]}" data-finish="spot gloss on segments"/>')

    elif k == "layered-depth":
        # The contact point is the corner of a second plane: a half-scale card pressed into the card.
        pw, ph = W / 2, H / 2
        x0, y0 = cx, cy          # square corner exactly on the contact point; the other corners bleed off
        plane = f'<rect x="{fmt(x0)}" y="{fmt(y0)}" width="{fmt(pw)}" height="{fmt(ph)}"'
        d.add("CMYK", f'{plane} fill="{C["plane"]}" id="plane"/>')
        d.add("DEBOSS", f'<rect x="{fmt(x0)}" y="{fmt(y0)}" width="{fmt(W - SAFE - x0)}" height="{fmt(H - SAFE - y0)}" fill="{C["die"]}" data-finish="deboss 0.15 mm, plane area inside the safe zone; vendor confirms PVC deboss"/>')
        d.add("SPOT_GLOSS", f'<rect x="{fmt(x0)}" y="{fmt(y0)}" width="{fmt(W - SAFE - x0)}" height="{fmt(H - SAFE - y0)}" fill="{C["spot"]}" data-finish="spot gloss on plane, clipped to the safe zone (25% of the face)"/>')

    elif k.startswith("essential-mono"):
        if monogram:
            d.add("CMYK", f'<path id="monogram" d="{MEDIUM.outline(monogram, MARGIN, H - MARGIN, T_MONOGRAM, -0.02)}" fill="{e.ink}" data-text="{html.escape(monogram)}"/>')

    # Shared signatures: lockup top-left on the margin, contact point on the 3/4 line.
    lk = lockup(MARGIN, MARGIN + MEDIUM.xh * T_WORDMARK + 1.2, e.ink)
    d.add("CMYK", lk)
    white_under(d, lk)
    # On opaque white-core PVC the flood knocks out under every element, so no white ink is needed;
    # on frosted stock everything printed in colour sits on a white underbase.
    dot = contact_dot(e.dot)
    d.add("CMYK", dot)
    white_under(d, dot)
    guides(d)
    return d


# ---------------------------------------------------------------------------- backs
def fit_name(name: str) -> list[tuple[str, float]]:
    """Name at 10 pt; shrink to 8 pt; then wrap at a word boundary. Max width = margin to margin."""
    maxw = W - 2 * MARGIN
    for size in (T_NAME, 10.0 * PT, T_NAME_MIN):
        if MEDIUM.width(name, size, TRACK_NAME) <= maxw * 0.82:
            return [(name, size)]
    words = name.split()
    best = None
    for i in range(1, len(words)):
        a, b = " ".join(words[:i]), " ".join(words[i:])
        wmax = max(MEDIUM.width(a, T_NAME, TRACK_NAME), MEDIUM.width(b, T_NAME, TRACK_NAME))
        if best is None or wmax < best[0]:
            best = (wmax, a, b)
    return [(best[1], T_NAME), (best[2], T_NAME)]


def back(e: Edition, ident: Identity | None, with_qr: bool = True) -> Doc:
    d = Doc(e, "back")
    base_flood(d)
    x = MARGIN
    printed = []

    if ident is not None:
        y = MARGIN + MEDIUM.cap * T_NAME + 0.4
        for text, size in fit_name(ident.name):
            printed.append(f'<path d="{MEDIUM.outline(text, x, y, size, TRACK_NAME)}" fill="{e.ink}" data-text="{html.escape(text)}" data-role="name"/>')
            y += size * 1.2
        y += 1.4
        for line in ident.lines[:2]:
            printed.append(f'<path d="{REGULAR.outline(line, x, y, T_CONTEXT)}" fill="{e.ink2}" data-text="{html.escape(line)}" data-role="context"/>')
            y += T_CONTEXT * 1.35
    else:
        # Generic inventory back: the lockup takes the name's place; the profile is fully digital.
        printed.append(lockup(MARGIN, MARGIN + MEDIUM.xh * T_WORDMARK + 1.2, e.ink))

    # Tap row: the Kipat mark is the tap cue. Baseline on the bottom margin line.
    base_y = H - MARGIN
    mh = T_UTILITY * 1.25
    dot, arcs = mark_paths(x + mh / 2, base_y - REGULAR.xh * T_UTILITY / 2, mh)
    printed.append(f'<path d="{dot}" fill="{e.ink}"/>')
    printed.append(f'<path d="{arcs}" fill="none" stroke="{e.ink}" stroke-width="{fmt(mark_stroke(mh))}" stroke-linecap="round"/>')
    printed.append(f'<path d="{MEDIUM.outline("Tap to connect", x + mh + 1.2, base_y, T_UTILITY)}" fill="{e.ink}" data-text="Tap to connect" data-role="utility"/>')

    for p in printed:
        d.add("CMYK", p)
        white_under(d, p)

    if with_qr:
        qd, n = qr_path(QR_PLACEHOLDER, QR_X, QR_Y, QR_SIZE)
        quiet = 4 * QR_SIZE / n
        if e.qr_patch:
            patch = (f'<rect x="{fmt(QR_X - quiet)}" y="{fmt(QR_Y - quiet)}" width="{fmt(QR_SIZE + 2 * quiet)}" height="{fmt(QR_SIZE + 2 * quiet)}" '
                     f'rx="0.8" fill="{e.qr_patch}" id="qr-quiet-zone"/>')
            if e.white_underbase:
                d.add("WHITE_INK", patch.replace(f'fill="{e.qr_patch}"', 'fill="#FFFFFF"'))
            else:
                d.add("CMYK", patch)
        qr_ink = C["ink"] if (e.qr_patch or e.tone != "dark") else e.ink
        d.add("CMYK", f'<path id="qr" d="{qd}" fill="{qr_ink}" data-qr="{QR_PLACEHOLDER}" data-placeholder="true" data-modules="{n}" data-module-mm="{fmt(QR_SIZE / n)}"/>')
        d.add("GUIDES", f'<rect x="{fmt(QR_X - quiet)}" y="{fmt(QR_Y - quiet)}" width="{fmt(QR_SIZE + 2 * quiet)}" height="{fmt(QR_SIZE + 2 * quiet)}" fill="none" stroke="#FF3B30" stroke-width="0.08" stroke-dasharray="0.4 0.4" data-guide="QR quiet zone (4 modules) - PLACEHOLDER QR, replaced per card"/>')
    guides(d)
    return d


# ---------------------------------------------------------------------------- rendering
PX_PER_MM = 20  # proofs: 1712 x 1080 px for the trim


def card_html(svg: str, *, frosted: bool = False, bg: str = "#E9E9E6", outline: bool = False, px=PX_PER_MM) -> tuple[str, int, int]:
    """A single trimmed card (rounded die-cut) on a flat ground, no shadow. Bleed is cropped."""
    w, h = round(W * px), round(H * px)
    pad = round(6 * px)
    cw, ch = w + 2 * pad, h + 2 * pad
    inner = svg.split("?>", 1)[-1]
    inner = inner.replace(f'width="{fmt(W + 2 * BLEED)}mm" height="{fmt(H + 2 * BLEED)}mm"',
                          f'width="{round((W + 2 * BLEED) * px)}" height="{round((H + 2 * BLEED) * px)}"', 1)
    frost = ""
    if frosted:
        # Simulated frosted PVC: a milky translucent sheet over the ground. Labelled as simulated on boards.
        frost = 'background: rgba(238,241,240,0.62); backdrop-filter: blur(5px);'
    ol = "box-shadow: inset 0 0 0 1px rgba(0,0,0,0.10);" if outline else ""
    page = f"""<!doctype html><html><head><meta charset="utf-8"><style>
html,body{{margin:0;background:{bg};}}
.under{{position:absolute;left:{pad + w * 0.52}px;top:{pad + h * 0.50}px;width:{w * 0.48 + pad * 0.7}px;height:{h * 0.34}px;border-radius:{RADIUS * px * 2}px;background:#6E6F72;display:{'block' if frosted else 'none'}}}
.card{{position:absolute;left:{pad}px;top:{pad}px;width:{w}px;height:{h}px;border-radius:{RADIUS * px}px;overflow:hidden;{frost}}}
.card svg{{position:absolute;left:{-BLEED * px}px;top:{-BLEED * px}px;}}
.ol{{position:absolute;left:{pad}px;top:{pad}px;width:{w}px;height:{h}px;border-radius:{RADIUS * px}px;{ol}pointer-events:none}}
</style></head><body><div class="under"></div><div class="card">{inner}</div><div class="ol"></div></body></html>"""
    return page, cw, ch


def shoot(page: str, out: Path, w: int, h: int):
    tmp = out.with_suffix(".tmp.html")
    tmp.write_text(page)
    subprocess.run(
        [CHROME, "--headless=new", "--no-sandbox", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=1",
         f"--screenshot={out}", f"--window-size={w},{h}", f"file://{tmp}"],
        check=True, capture_output=True, timeout=120,
    )
    tmp.unlink()


def proof(doc: Doc, out: Path, mode="proof", px=PX_PER_MM):
    """Always rendered at 20 px/mm (Chromium clips small windows), then downscaled if asked."""
    e = doc.e
    page, w, h = card_html(doc.svg(mode), frosted=e.frosted, outline=e.tone in ("light", "neutral", "material"))
    shoot(page, out, w, h)
    if px != PX_PER_MM:
        from PIL import Image
        im = Image.open(out)
        im.resize((round(im.width * px / PX_PER_MM), round(im.height * px / PX_PER_MM)), Image.LANCZOS).save(out)


