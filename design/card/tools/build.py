def fmt(v: float) -> str:
    return f"{v:.3f}".rstrip("0").rstrip(".")


# ---------------------------------------------------------------------------- Kipat mark
def mark_paths(cx: float, cy: float, h: float) -> tuple[str, str]:
    """The Kipat mark (app: KipatIcons.Mark) scaled to height h mm, centred on (cx, cy).
    Returns (dot path, arcs path for stroking) and stroke width via mark_stroke(h)."""
    k = h / 24.0
    def P(x, y):
        return fmt(cx + (x - 12) * k), fmt(cy + (y - 12) * k)
    r = 2.5 * k
    dot = f"M{fmt(cx - r)} {fmt(cy)} a{fmt(r)} {fmt(r)} 0 1 0 {fmt(2 * r)} 0 a{fmt(r)} {fmt(r)} 0 1 0 {fmt(-2 * r)} 0Z"
    r1, r2 = fmt(6.8 * k), fmt(10.8 * k)
    a = (
        f"M{' '.join(P(7.2, 16.8))} A{r1} {r1} 0 0 1 {' '.join(P(7.2, 7.2))} "
        f"M{' '.join(P(16.8, 7.2))} A{r1} {r1} 0 0 1 {' '.join(P(16.8, 16.8))} "
        f"M{' '.join(P(19.6, 4.4))} A{r2} {r2} 0 0 1 {' '.join(P(19.6, 19.6))}"
    )
    return dot, a


def mark_stroke(h: float) -> float:
    return 2.0 * h / 24.0


def lockup(x: float, baseline: float, color: str, size: float = T_WORDMARK) -> str:
    """Kipat mark + typeset wordmark 'kipat' (Inter Medium). The mark is the app's placeholder mark
    until a final logo exists; the wordmark is typeset, not drawn."""
    xh = MEDIUM.xh * size
    mh = size * 1.0                       # mark height = 1 em
    mcx = x + mh * 0.5
    mcy = baseline - xh * 0.5
    dot, arcs = mark_paths(mcx, mcy, mh)
    tx = x + mh + size * 0.30
    word = MEDIUM.outline("kipat", tx, baseline, size, TRACK_WORDMARK)
    return (
        f'<g id="kipat-lockup">'
        f'<path d="{dot}" fill="{color}"/>'
        f'<path d="{arcs}" fill="none" stroke="{color}" stroke-width="{fmt(mark_stroke(mh))}" stroke-linecap="round"/>'
        f'<path d="{word}" fill="{color}" data-text="kipat"/>'
        f"</g>"
    )


def contact_dot(color: str, r: float = CONTACT_R) -> str:
    cx, cy = CONTACT
    return f'<circle id="contact-point" cx="{fmt(cx)}" cy="{fmt(cy)}" r="{fmt(r)}" fill="{color}"/>'


# ---------------------------------------------------------------------------- QR
def qr_path(data: str, x: float, y: float, size: float) -> tuple[str, int]:
    q = segno.make(data, error="m", micro=False)
    rows = [list(r) for r in q.matrix_iter(scale=1, border=0)]
    n = len(rows)
    m = size / n
    d = []
    for j, row in enumerate(rows):
        i = 0
        while i < n:
            if row[i]:
                k = i
                while k < n and row[k]:
                    k += 1
                d.append(f"M{fmt(x + i * m)} {fmt(y + j * m)}h{fmt((k - i) * m)}v{fmt(m)}h{fmt(-(k - i) * m)}Z")
                i = k
            else:
                i += 1
    return "".join(d), n


