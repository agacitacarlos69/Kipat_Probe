SIX = ["graphite-precision", "frosted-contact", "architectural-line", "aperture", "layered-depth", "essential-mono"]


def build(svg_only=False):
    student = IDENTITIES[0]
    for key in SIX + ["essential-mono-dark"]:
        e = ED[key]
        folder = CARD / "directions" / ("essential-mono" if key.startswith("essential-mono") else key)
        suffix = "-dark" if key.endswith("-dark") else ""
        f = front(e)
        b = back(e, student)
        g = back(e, None, with_qr=False)
        (folder / f"front{suffix}.svg").write_text(f.svg("master"))
        (folder / f"back{suffix}.svg").write_text(b.svg("master"))
        (folder / f"back-generic{suffix}.svg").write_text(g.svg("master"))
        if key.startswith("essential-mono"):
            fm = front(e, monogram="VP")
            (folder / f"front-monogram{suffix}.svg").write_text(fm.svg("master"))
        if svg_only:
            continue
        proof(f, folder / f"front-proof{suffix}.png")
        proof(b, folder / f"back-proof{suffix}.png")
        proof(g, folder / f"back-generic-proof{suffix}.png", px=10)
        proof(f, folder / f"front-finish{suffix}.png", mode="finish", px=10)
        proof(f, folder / f"front-guides{suffix}.png", mode="guides", px=10)
        if key.startswith("essential-mono"):
            proof(fm, folder / f"front-monogram-proof{suffix}.png", px=10)
        # identity stress test on the back
        for ident in IDENTITIES:
            proof(back(e, ident), CARD / "boards" / "identities" / f"{key}-{ident.key}.png", px=10)
        print("built", key)


def verify_qr():
    """Decode every QR on every back proof with OpenCV. Fails loudly if any is unreadable."""
    import cv2
    det = cv2.QRCodeDetector()
    bad = []
    for png in sorted((CARD / "directions").glob("*/back-proof*.png")):
        img = cv2.imread(str(png))
        val, _, _ = det.detectAndDecode(img)
        # 20, 10, 8, 7 and 6 px/mm: from a close scan down to a phone held at arm's length.
        scales = (0.5, 0.4, 0.35, 0.3)
        hits = sum(det.detectAndDecode(cv2.resize(img, None, fx=f, fy=f, interpolation=cv2.INTER_AREA))[0] == QR_PLACEHOLDER for f in scales)
        ok = val == QR_PLACEHOLDER and hits >= 3
        print(f"qr {'ok ' if ok else 'BAD'} {hits + (val == QR_PLACEHOLDER)}/5 scales {png.relative_to(CARD)}")
        if not ok:
            bad.append(png)
    if bad:
        raise SystemExit(f"{len(bad)} QR proofs did not decode")


if __name__ == "__main__":
    (CARD / "boards" / "identities").mkdir(parents=True, exist_ok=True)
    build(svg_only="--svg-only" in sys.argv)
    if "--svg-only" not in sys.argv:
        verify_qr()
